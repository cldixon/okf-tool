/**
 * Writes src/format/vega-lite-schema.ts: the pinned Vega-Lite's JSON schema (worker/render's
 * vega-lite, VEGA_LITE_VERSION) without its descriptions, as a string the Worker parses on the
 * first chart it checks (TEMPRA-214). `bun scripts/vega-lite-schema.ts` after moving Vega-Lite;
 * worker/test/chart-schema.test.ts fails while the file is stale.
 */
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { VEGA_LITE_VERSION } from "../render/src/version";

const OUT = join(import.meta.dir, "../src/format/vega-lite-schema.ts");

/** The schema as the Worker keeps it: the validator's keywords, no prose. */
export async function schemaText(): Promise<string> {
  const at = (f: string) => join(import.meta.dir, "../render/node_modules/vega-lite", f);
  const pkg = JSON.parse(await readFile(at("package.json"), "utf8")) as { version: string };
  if (pkg.version !== VEGA_LITE_VERSION) {
    throw new Error(`worker/render has vega-lite ${pkg.version}, not ${VEGA_LITE_VERSION}`);
  }
  const schema: unknown = JSON.parse(await readFile(at("build/vega-lite-schema.json"), "utf8"));
  const strip = (o: unknown, names = false): unknown => {
    if (Array.isArray(o)) return o.map((x) => strip(x));
    if (!o || typeof o !== "object") return o;
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(o)) {
      // Under `properties` and `definitions` the keys are names, not keywords.
      if (!names && (k === "description" || k === "format" || k === "$schema")) continue;
      out[k] = strip(v, !names && (k === "properties" || k === "definitions"));
    }
    return out;
  };
  return JSON.stringify(strip(schema));
}

export function moduleText(json: string): string {
  return `// Generated by scripts/vega-lite-schema.ts from vega-lite ${VEGA_LITE_VERSION}; do not edit.\nexport const VEGA_LITE_SCHEMA_JSON = ${JSON.stringify(json)};\n`;
}

if (import.meta.main) {
  await writeFile(OUT, moduleText(await schemaText()));
  console.log(`Wrote ${OUT}`);
}
