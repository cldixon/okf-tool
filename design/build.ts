/**
 * `bun run build` in design/: bundles src/*.css (fonts, tokens, base, prose, reader, workspace,
 * concept, comments, views, public, in that order) into dist/tempra.css for the site, and
 * dist/tempra.ts for the app: the stylesheet with its fonts (design/fonts/*.woff2) at
 * content-hashed URLs, and which font file each URL names. The app's build writes them, with
 * favicon.svg, into the Worker's static assets (TEMPRA-174); the Worker itself takes only `href`.
 * dist/panel.ts is the panels' stylesheet (TEMPRA-200), dist/pele.ts the diagram theme. Every
 * output is committed; design.test.ts fails when one is stale.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MARK_PATHS, MARK_VIEWBOX } from "./src/components/mark";

const ROOT = import.meta.dir;
export const SOURCES = [
  "fonts.css",
  "tokens.css",
  "base.css",
  "mark.css",
  "prose.css",
  "reader.css",
  "workspace.css",
  "concept.css",
  "comments.css",
  "views.css",
  "public.css",
];

const sha = (data: string | Uint8Array) =>
  new Bun.CryptoHasher("sha256").update(data).digest("hex").slice(0, 12);

export function generate(): { css: string; ts: string } {
  // The site's stylesheet: fonts by their path in the package, which its bundler resolves.
  const css = `${SOURCES.map((f) => readFileSync(join(ROOT, "src", f), "utf8").trim()).join("\n\n")}\n`;
  // The app's: each font at /_design/<name>.<hash>.woff2, so it can be cached for good.
  const fonts: Record<string, string> = {};
  let appCss = css;
  for (const file of readdirSync(join(ROOT, "fonts"))
    .filter((f) => f.endsWith(".woff2"))
    .sort()) {
    const bytes = readFileSync(join(ROOT, "fonts", file));
    const served = file.replace(/\.woff2$/, `.${sha(bytes)}.woff2`);
    fonts[served] = file;
    appCss = appCss.replaceAll(`url("../fonts/${file}")`, `url("/_design/${served}")`);
  }
  const hash = sha(appCss);
  const ts = `// Generated by design/build.ts from design/src/*.css and design/fonts/; edit those and run \`bun run build\`.

/** The whole stylesheet: fonts, tokens, base and prose. */
export const css: string = ${JSON.stringify(appCss)};

/** First 12 hex characters of the stylesheet's SHA-256, for an immutable URL. */
export const hash = ${JSON.stringify(hash)};

/** Where the app serves it. */
export const href = \`/_design/tempra.\${hash}.css\`;

/**
 * The fonts the stylesheet names: the file name it asks for under /_design/, to the file in
 * design/fonts/ (\`@tempra/design/fonts/<file>\`) that holds its bytes.
 */
export const fonts: Record<string, string> = ${JSON.stringify(fonts)};
`;
  return { css, ts };
}

/** The `--name: value;` declarations of a CSS block body, comments removed. */
function declarationsOf(block: string): Map<string, string> {
  const out = new Map<string, string>();
  const text = block.replace(/\/\*[\s\S]*?\*\//g, "");
  for (const m of text.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    out.set(m[1] as string, (m[2] as string).replace(/\s+/g, " ").trim());
  }
  return out;
}

/** `light-dark(a, b)` resolved for one scheme, split at its top-level comma. */
function pickScheme(value: string, scheme: "light" | "dark"): string {
  let out = value;
  for (let at = out.indexOf("light-dark("); at >= 0; at = out.indexOf("light-dark(")) {
    const open = at + "light-dark(".length;
    let depth = 0;
    let comma = -1;
    let close = -1;
    for (let i = open; i < out.length && close < 0; i++) {
      const c = out[i];
      if (c === "(") depth++;
      else if (c === ")") {
        if (depth === 0) close = i;
        else depth--;
      } else if (c === "," && depth === 0 && comma < 0) comma = i;
    }
    if (close < 0 || comma < 0) throw new Error(`Unbalanced light-dark() in ${value}`);
    const pick = scheme === "light" ? out.slice(open, comma) : out.slice(comma + 1, close);
    out = out.slice(0, at) + pick.trim() + out.slice(close + 1);
  }
  return out;
}

/**
 * The diagram theme the reader gives Pele (`--pele-*` in reader.css, mapped to `--tempra-*` in
 * tokens.css), resolved to concrete values for light and for dark, for what draws diagrams outside
 * a page: the render Worker (TEMPRA-165, worker/render/); and the chart series, which the reader's
 * charts take from here too (TEMPRA-217). Generated, so it never drifts from the CSS.
 */
/** tokens.css's `:root` tokens, and a resolver from a value (with `var()`s) to one scheme's value. */
function tokenResolver() {
  const tokensCss = readFileSync(join(ROOT, "src", "tokens.css"), "utf8");
  const root = /:root\s*\{([\s\S]*?)\n\}/.exec(tokensCss)?.[1];
  if (!root) throw new Error("tokens.css :root not found");
  const tokens = declarationsOf(root);
  const resolve = (value: string, scheme: "light" | "dark", depth = 0): string => {
    if (depth > 10) throw new Error(`Token cycle at ${value}`);
    const v = value.replace(/var\((--[a-z0-9-]+)\)/g, (_, name: string) => {
      const t = tokens.get(name);
      if (t === undefined) throw new Error(`Unknown token ${name}`);
      return resolve(t, scheme, depth + 1);
    });
    return pickScheme(v, scheme);
  };
  /** One token by name, resolved for a scheme. */
  const token = (name: string, scheme: "light" | "dark") => {
    const t = tokens.get(name);
    if (t === undefined) throw new Error(`Unknown token ${name}`);
    return resolve(t, scheme);
  };
  return { tokens, resolve, token };
}

export function generatePele(): string {
  const readerCss = readFileSync(join(ROOT, "src", "reader.css"), "utf8");
  const diagram = /\.prose figure\.diagram,\s*\.lightbox\s*\{([\s\S]*?)\}/.exec(readerCss)?.[1];
  if (!diagram) throw new Error("reader.css's diagram block not found");
  const { tokens, resolve } = tokenResolver();
  const pele = declarationsOf(diagram);
  const theme = (scheme: "light" | "dark") =>
    Object.fromEntries([...pele].map(([name, value]) => [name, resolve(value, scheme)]));
  const themes = { light: theme("light"), dark: theme("dark") };
  // The chart series (`--tempra-color-chart-*`, TEMPRA-217), in their order, for Vega-Lite's categories.
  const chartNames = [...tokens.keys()]
    .filter((k) => /^--tempra-color-chart-\d+$/.test(k))
    .sort(
      (a, b) =>
        Number(a.slice("--tempra-color-chart-".length)) -
        Number(b.slice("--tempra-color-chart-".length)),
    );
  if (chartNames.length < 8)
    throw new Error("tokens.css has fewer than 8 --tempra-color-chart-* series");
  const series = (scheme: "light" | "dark") =>
    chartNames.map((k) => resolve(tokens.get(k) as string, scheme));
  const charts = { light: series("light"), dark: series("dark") };
  const latin = readFileSync(join(ROOT, "fonts", "inter-latin-opsz-normal.woff2"));
  const hash = sha(JSON.stringify(themes) + JSON.stringify(charts) + sha(latin));
  return `// Generated by design/build.ts from design/src/tokens.css and reader.css; edit those and run \`bun run build\`.

/** The reader's diagram theme (\`--pele-*\`), resolved to values for light and for dark. */
export const peleThemes: Record<"light" | "dark", Record<string, string>> = ${JSON.stringify(themes, null, 2)};

/**
 * The chart series (\`--tempra-color-chart-*\` in tokens.css, TEMPRA-217), resolved for light and for
 * dark, in their fixed order: a Vega-Lite chart's categories (@tempra/editor \`chartConfig\`).
 */
export const chartSeries: Record<"light" | "dark", string[]> = ${JSON.stringify(charts, null, 2)};

/** First 12 hex characters of a SHA-256 of the themes, the chart series and the font, for cache keys. */
export const peleThemeHash = ${JSON.stringify(hash)};

/** Inter's Latin subset (variable, upright; OFL, design/fonts/OFL.txt), as base64. */
export const interLatinWoff2: string = ${JSON.stringify(latin.toString("base64"))};
`;
}

/**
 * The stylesheet of the panels an MCP host draws in a chat (TEMPRA-200): the tokens and
 * src/panel.css, without the webfonts (a panel can load nothing but what it declares), for the
 * app's build to inline into each panel's HTML.
 */
export function generatePanel(): string {
  const css = ["tokens.css", "mark.css", "panel.css"]
    .map((f) => readFileSync(join(ROOT, "src", f), "utf8").trim())
    .join("\n\n");
  return `// Generated by design/build.ts from design/src/tokens.css, mark.css and panel.css; edit those and run \`bun run build\`.

/** The panels' stylesheet: the tokens, the mark and panel.css, no webfonts. */
export const panelCss: string = ${JSON.stringify(`${css}\n`)};

/** The page panel's stylesheet: Inter at \`/_design/\` names, tokens, base, prose, reader, panel. */
export const pagePanelCss: string = ${JSON.stringify(generatePagePanel())};
`;
}

/**
 * The page panel's stylesheet (tempra-dev app/page-panel): it reads as the app does, so it has
 * Inter (at the app's `/_design/` names, which the Worker points at its own origin when it serves
 * the panel), the tokens, base, prose and reader CSS, and panel.css.
 */
export function generatePagePanel(): string {
  let css = [
    "fonts.css",
    "tokens.css",
    "base.css",
    "mark.css",
    "prose.css",
    "reader.css",
    "panel.css",
  ]
    .map((f) => readFileSync(join(ROOT, "src", f), "utf8").trim())
    .join("\n\n");
  for (const file of readdirSync(join(ROOT, "fonts")).filter((f) => f.endsWith(".woff2"))) {
    const served = file.replace(
      /\.woff2$/,
      `.${sha(readFileSync(join(ROOT, "fonts", file)))}.woff2`,
    );
    css = css.replaceAll(`url("../fonts/${file}")`, `url("/_design/${served}")`);
  }
  return `${css}\n`;
}

/**
 * The Tempra mark (TEMPRA-279: `MARK_PATHS` in src/components/mark.ts) as a standalone SVG in the
 * light scheme's plate colours (`--tempra-color-mark-*`), for places that take an image and no
 * stylesheet: the operator's portal's Cloudflare Access sign-in page (TEMPRA-282), served at
 * /mark.svg by the app. Unlike the favicon, it does not follow the system's dark mode: the page it
 * sits on is the light scheme's.
 */
export function generateMark(): string {
  const { token } = tokenResolver();
  const p = MARK_PATHS.standard;
  const [, , w, h] = MARK_VIEWBOX.split(" ").map(Number);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${MARK_VIEWBOX}" width="${(w ?? 0) * 2}" height="${(h ?? 0) * 2}">
<title>Tempra</title>
<path fill="${token("--tempra-color-mark-back", "light")}" d="${p.back}"/>
<path fill="${token("--tempra-color-mark-mid", "light")}" d="${p.middle}"/>
<path fill="${token("--tempra-color-mark-front", "light")}" d="${p.front}"/>
</svg>
`;
}

/**
 * The brand's colours, resolved from tokens.css for each scheme, for what is styled by values and
 * not by this stylesheet (Cloudflare Access's sign-in page, TEMPRA-282).
 */
export function generateBrand(): string {
  const { token } = tokenResolver();
  const scheme = (s: "light" | "dark") => ({
    bg: token("--tempra-color-bg", s),
    text: token("--tempra-color-text", s),
    muted: token("--tempra-color-muted", s),
  });
  const brand = { light: scheme("light"), dark: scheme("dark") };
  return `// Generated by design/build.ts from design/src/tokens.css; edit that and run \`bun run build\`.

/** The page's background, text and muted text (\`--tempra-color-bg\`, \`-text\`, \`-muted\`), per scheme. */
export const brand: Record<"light" | "dark", { bg: string; text: string; muted: string }> = ${JSON.stringify(brand, null, 2)};

/** The served path of the Tempra mark (dist/mark.svg; the app puts it in its static assets). */
export const markPath = "/mark.svg";
`;
}

if (import.meta.main) {
  const { css, ts } = generate();
  writeFileSync(join(ROOT, "dist", "tempra.css"), css);
  writeFileSync(join(ROOT, "dist", "tempra.ts"), ts);
  writeFileSync(join(ROOT, "dist", "pele.ts"), generatePele());
  writeFileSync(join(ROOT, "dist", "panel.ts"), generatePanel());
  writeFileSync(join(ROOT, "dist", "brand.ts"), generateBrand());
  writeFileSync(join(ROOT, "dist", "mark.svg"), generateMark());
  console.log(
    "Wrote dist/tempra.css, dist/tempra.ts, dist/pele.ts, dist/panel.ts, dist/brand.ts and dist/mark.svg",
  );
}
