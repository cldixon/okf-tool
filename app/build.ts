/**
 * `bun run build` in app/ (also run by `bun install`): bundles src/main.ts (Svelte 5, TEMPRA-176) with Vite into an ES
 * module entry and the chunks it imports on demand (Pele, for pages with a diagram), and writes
 * the Worker's static assets (TEMPRA-174) to dist/public/: the bundle under /_app/, the design
 * stylesheet and its fonts under /_design/ (from @tempra/design), /favicon.svg, /mark.svg, and a `_headers`
 * file. Cloudflare serves them before the Worker runs (`assets` in worker/cloudflare.config.ts).
 * dist/app.ts names the entry (`hash`, `href`) and its chunks for the Worker, which writes the
 * entry's URL into the shell; it carries no code. dist/ is not committed.
 * dist/panels.ts holds the MCP Apps panels (TEMPRA-200): each one HTML document, its script and
 * the design package's panel stylesheet inlined, which the Worker serves as a `ui://` resource.
 * `--watch` rebuilds on every change to src/ or to the design package's output, for `bun run dev`
 * beside the Worker's `cf dev` (which serves dist/public/ as it changes).
 */
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  watch as watchFiles,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { svelte } from "@sveltejs/vite-plugin-svelte";
import { css as designCss, fonts as designFonts, href as designHref } from "@tempra/design";
import { pagePanelCss, panelCss } from "@tempra/design/panel";
import { build, type Rollup } from "vite";

const ROOT = import.meta.dir;
const watch = process.argv.includes("--watch");

/** Where the Worker's static assets are written: the directory `assets` names in its config. */
export const PUBLIC = join(ROOT, "dist", "public");

/**
 * Headers for the static assets (Workers static assets read `_headers`): the bundle and the
 * design files are at content-hashed URLs, so a new file gets a new URL and each can be cached
 * for good; the icon's URL never changes. The bundle and the design files answer any origin: the
 * page panel (tempra-dev app/page-panel) loads Pele and Inter from a host's frame, and module
 * scripts and fonts need CORS.
 */
export const HEADERS = `/_app/*
  Cache-Control: public, max-age=31536000, immutable
  X-Content-Type-Options: nosniff
  Access-Control-Allow-Origin: *
/_design/*
  Cache-Control: public, max-age=31536000, immutable
  X-Content-Type-Options: nosniff
  Access-Control-Allow-Origin: *
/favicon.svg
  Cache-Control: public, max-age=86400
  X-Content-Type-Options: nosniff
/mark.svg
  Cache-Control: public, max-age=86400
  X-Content-Type-Options: nosniff
`;

/**
 * dist/app.ts for an entry and its chunks. `hash` is the one in the entry's file name (Vite's
 * content hash, which the chunks import it by), or for a bare `js` the first 12 hex characters of
 * its SHA-256.
 */
export function moduleSource(js: string, chunks: Record<string, string> = {}, file?: string) {
  const hash =
    (file && /^app\.([\w-]+)\.js$/.exec(file)?.[1]) ||
    new Bun.CryptoHasher("sha256").update(js).digest("hex").slice(0, 12);
  return `// Generated by app/build.ts from app/src; run \`bun run build\` in app/.

/** The entry's content hash, for an immutable URL. */
export const hash = ${JSON.stringify(hash)};

/**
 * Where the entry is served, a static asset in dist/public/ (the name its chunks import it by).
 */
export const href = \`/_app/app.\${hash}.js\`;

/**
 * What the entry imports on demand, by file name (\`<name>-<hash>.js\`, so immutable), served at
 * /_app/<file> beside it.
 */
export const chunks: string[] = ${JSON.stringify(Object.keys(chunks))};
`;
}

/**
 * Writes dist/public/ afresh: the entry and its chunks under _app/, the design stylesheet at its
 * hashed name and every font it names under _design/, the icon and `_headers`. Afresh, so files
 * from an earlier build are never uploaded with this one.
 */
export function writePublic(entry: { file: string; code: string }, chunks: Record<string, string>) {
  rmSync(PUBLIC, { recursive: true, force: true });
  mkdirSync(join(PUBLIC, "_app"), { recursive: true });
  mkdirSync(join(PUBLIC, "_design"), { recursive: true });
  writeFileSync(join(PUBLIC, "_app", entry.file), entry.code);
  for (const [file, code] of Object.entries(chunks))
    writeFileSync(join(PUBLIC, "_app", file), code);
  writeFileSync(join(PUBLIC, designHref.slice(1)), designCss);
  for (const [served, source] of Object.entries(designFonts)) {
    const bytes = readFileSync(Bun.resolveSync(`@tempra/design/fonts/${source}`, ROOT));
    writeFileSync(join(PUBLIC, "_design", served), bytes);
  }
  writeFileSync(
    join(PUBLIC, "favicon.svg"),
    readFileSync(Bun.resolveSync("@tempra/design/favicon.svg", ROOT)),
  );
  // The Tempra mark, for Cloudflare Access's sign-in page in front of the operator's portal
  // (TEMPRA-282): an image there must come from a host Access does not cover.
  writeFileSync(
    join(PUBLIC, "mark.svg"),
    readFileSync(Bun.resolveSync("@tempra/design/mark.svg", ROOT)),
  );
  writeFileSync(join(PUBLIC, "_headers"), HEADERS);
}

/**
 * A panel's one HTML document (SEP-1865: a `text/html;profile=mcp-app` resource): the panels'
 * stylesheet and the panel's bundle inline, since the host's sandbox loads nothing else. The
 * script's text may not close its element or open a comment there.
 */
export function panelHtml(
  title: string,
  js: string,
  css: string = panelCss,
  bodyClass = "panel",
): string {
  const script = js.replace(/<\/(script)/gi, "<\\/$1").replace(/<!--/g, "<\\!--");
  const style = css.replace(/<\/(style)/gi, "<\\/$1");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<style>${style}</style></head>
<body class="${bodyClass}"><main id="panel"></main>
<script type="module">${script}</script></body></html>
`;
}

/**
 * Bundles one panel's entry into a single module (no chunks: the host loads one document). With
 * Bun's bundler, which shakes ext-apps' graph (the MCP SDK and zod) to a third of Vite's output.
 */
async function bundlePanel(entry: string): Promise<string> {
  const out = await Bun.build({
    entrypoints: [join(ROOT, entry)],
    target: "browser",
    format: "esm",
    minify: true,
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
  });
  const js = out.outputs[0];
  if (!out.success || !js) throw new Error(`No JavaScript for ${entry}: ${out.logs.join("\n")}`);
  return await js.text();
}

/**
 * Stand-ins for what the page panel leaves out: Vega (about 780 KB) for charts, whose data the
 * panel cannot fetch anyway; a chart shows as its source with the reader's quiet notice.
 */
const PAGE_PANEL_STUBS: Record<string, string> = {
  "./chart": `export function chartFigure() { throw new Error("Charts are drawn in Tempra; open the page there to see this one"); }`,
};

/**
 * The page panel (tempra-dev app/page-panel) with Vite and the Svelte plugin, as one module: the
 * app's reader and its components, no chunks (the host loads one document). Pele, about half the
 * panel inlined, is imported from the app's own chunk on the deployment when a page has a diagram:
 * buildApp() has written it, and the Worker puts its origin for `__TEMPRA_ORIGIN__`.
 */
async function bundlePagePanel(): Promise<string> {
  const result = (await build({
    root: ROOT,
    configFile: false,
    logLevel: "warn",
    mode: "production",
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    plugins: [
      svelte({ configFile: false, emitCss: false, compilerOptions: { css: "external" } }),
      {
        name: "page-panel-stubs",
        enforce: "pre",
        resolveId(id, importer) {
          // Pele is the app's own chunk, loaded from the deployment; the Worker writes in its origin.
          if (importer?.includes("/reader/") && id === "./pele") {
            const file = readdirSync(join(PUBLIC, "_app")).find((f) => /^pele-[\w-]+\.js$/.test(f));
            if (!file) throw new Error("No Pele chunk in dist/public/_app.");
            return { id: `__TEMPRA_ORIGIN__/_app/${file}`, external: true };
          }
          if (importer?.includes("/reader/") && id in PAGE_PANEL_STUBS) return `\0stub:${id}`;
          return null;
        },
        load(id) {
          return id.startsWith("\0stub:") ? PAGE_PANEL_STUBS[id.slice("\0stub:".length)] : null;
        },
      },
    ],
    build: {
      write: false,
      target: "es2022",
      minify: true,
      sourcemap: false,
      modulePreload: false,
      rollupOptions: {
        input: join(ROOT, "src/panels/page-main.ts"),
        output: { format: "es", codeSplitting: false },
      },
    },
  })) as Rollup.RollupOutput | Rollup.RollupOutput[];
  const output = Array.isArray(result) ? result[0] : result;
  const js = output?.output.find((o): o is Rollup.OutputChunk => o.type === "chunk" && o.isEntry);
  if (!js) throw new Error("No JavaScript for the page panel.");
  return js.code;
}

/** Builds the panels and writes dist/panels.ts. */
export async function buildPanels(): Promise<void> {
  const upload = panelHtml("Upload a file", await bundlePanel("src/panels/upload-main.ts"));
  const page = panelHtml("Tempra page", await bundlePagePanel(), pagePanelCss, "page-body");
  writeFileSync(
    join(ROOT, "dist", "panels.ts"),
    `// Generated by app/build.ts from app/src/panels; run \`bun run build\` in app/.

/** The upload panel (TEMPRA-200): one HTML document, served as \`ui://tempra/upload\`. */
export const uploadPanel: string = ${JSON.stringify(upload)};

/** The page panel (tempra-dev app/page-panel): one HTML document, served as \`ui://tempra/page\`. */
export const pagePanel: string = ${JSON.stringify(page)};
`,
  );
  console.log(
    `app: wrote dist/panels.ts (upload ${(upload.length / 1024).toFixed(0)} KB, page ${(page.length / 1024).toFixed(0)} KB)`,
  );
}

/** Builds once and writes dist/public/ and dist/app.ts. */
export async function buildApp(): Promise<void> {
  const result = (await build({
    root: ROOT,
    configFile: false,
    logLevel: "warn",
    mode: "production",
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    // Components carry no <style> (every look is @tempra/design's), so no CSS is emitted.
    plugins: [svelte({ configFile: false, emitCss: false, compilerOptions: { css: "external" } })],
    build: {
      write: false,
      target: "es2022",
      minify: true,
      sourcemap: false,
      modulePreload: false,
      rollupOptions: {
        input: join(ROOT, "src/main.ts"),
        output: {
          format: "es",
          entryFileNames: "app.[hash].js",
          chunkFileNames: "[name]-[hash].js",
          // Vite's preload helper in a chunk of its own, not the entry: the page panel loads the Pele
          // chunk from the deployment (tempra-dev app/page-panel), and it must not bring the app.
          codeSplitting: {
            groups: [{ name: "preload", test: /vite\/preload-helper|preload-helper/ }],
          },
        },
      },
    },
  })) as Rollup.RollupOutput | Rollup.RollupOutput[];
  const output = Array.isArray(result) ? result[0] : result;
  const all = output?.output.filter((o): o is Rollup.OutputChunk => o.type === "chunk") ?? [];
  const entry = all.find((c) => c.isEntry);
  if (!entry) throw new Error("Vite produced no JavaScript.");
  const chunks = Object.fromEntries(all.filter((c) => !c.isEntry).map((c) => [c.fileName, c.code]));
  writePublic({ file: entry.fileName, code: entry.code }, chunks);
  writeFileSync(join(ROOT, "dist", "app.ts"), moduleSource(entry.code, chunks, entry.fileName));
  const lazy = Object.values(chunks).reduce((n, c) => n + c.length, 0);
  console.log(
    `app: wrote dist/public/ and dist/app.ts (${(entry.code.length / 1024).toFixed(0)} KB, and ${Object.keys(chunks).length} chunks on demand, ${(lazy / 1024).toFixed(0)} KB)`,
  );
}

if (import.meta.main) {
  await buildApp();
  await buildPanels();
  if (watch) {
    let timer: ReturnType<typeof setTimeout> | undefined;
    const rebuild = () => {
      clearTimeout(timer);
      timer = setTimeout(
        () =>
          buildApp()
            .then(buildPanels)
            .catch((e) => console.error(e)),
        100,
      );
    };
    watchFiles(join(ROOT, "src"), { recursive: true }, rebuild);
    // A design change (\`bun run build\` in design/) changes the stylesheet's hashed name.
    watchFiles(dirname(Bun.resolveSync("@tempra/design", ROOT)), rebuild);
    console.log("app: watching src/ and @tempra/design");
  }
}
